"""Bake the six exposed reaches from arena.jpg. No runtime image decoding.

The five stone/trail crossings split the teal water into six components.
Fill across reflections and lily pads within each reach, never across bridges.
Run after changing the battlefield painting; Pillow is only a build-time tool.
"""
from pathlib import Path
from PIL import Image, ImageFilter, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
W, H = 366, 269
im = Image.open(ROOT / "assets/arena.jpg").convert("RGB").resize((W, H), Image.Resampling.BOX)
mask = Image.new("L", (W, H))
mask.putdata([255 if g-r > 15 and b-r > 8 and b > g*.72 else 0 for r,g,b in im.getdata()])
mask = mask.filter(ImageFilter.MedianFilter(3))
reaches = [(92,55),(369,282),(620,467),(827,628),(1046,791),(1325,998)]
rows = [[] for _ in range(H)]
for i,(x,y) in enumerate(reaches):
    seed=(x*W//1464,y*H//1074)
    assert mask.getpixel(seed)==255, ("water seed no longer matches artwork", seed)
    ImageDraw.floodfill(mask, seed, i+1)
    count=0
    for y in range(H):
        reach=[x for x in range(W) if mask.getpixel((x,y))==i+1]
        if reach:
            rows[y].append((min(reach),max(reach)+1))
            count+=len(reach)
    assert count>350
assert max(map(len,rows))<=2
out="/* Generated by tools/river_mask.py from assets/arena.jpg. Half-open x spans. */\n"
out+=f"enum {{ RIVER_W={W}, RIVER_H={H} }};\n"
out+="static const unsigned short river_spans[RIVER_H][4]={\n"
for row in rows:
    spans=[n for pair in row for n in pair]
    out+="    {"+",".join(map(str,spans+[0]*(4-len(spans))))+"},\n"
(ROOT/"src/river_mask.h").write_text(out+"};\n",encoding="ascii")
