"""Build second-roster resources from original supplied sheets (optional, Pillow).

Usage: python tools/pack_roster.py portraits.png domains.png skills.png storm.png
    tide.png furnace.png frost.png ink.png
Sheets: 5 portrait columns, 5 scenery columns, 5x3 skills, five 6x3 RGBA actors.
"""
import argparse
from pathlib import Path
from statistics import median
from PIL import Image, ImageOps
from pack_motion import ROOT, CELL, cells, root_fraction, enemy


def tile(im, col, cols, row=0, rows=1):
    return im.crop((round(im.width*col/cols),round(im.height*row/rows),
                    round(im.width*(col+1)/cols),round(im.height*(row+1)/rows)))


def build(portraits, domains, skills, actors):
    dest=ROOT/"assets"
    bust=Image.open(portraits).convert("RGBA")
    scenes=Image.open(domains).convert("RGB")
    icons=Image.open(skills).convert("RGB")
    plates=Image.new("RGBA",(400*5,664))
    back=Image.new("RGB",(400*5,664))
    cards=Image.new("RGB",back.size)
    glyphs=Image.new("RGB",(800,480))
    for n in range(5):
        figure=tile(bust,n,5).resize((400,664),Image.Resampling.LANCZOS)
        scene=ImageOps.fit(tile(scenes,n,5),(400,664),method=Image.Resampling.LANCZOS)
        back.paste(scene,(400*n,0))
        plates.paste(figure,(400*n,0))
        scene.paste(figure,mask=figure.getchannel("A"))
        cards.paste(scene,(400*n,0))
        for j in range(3):
            glyphs.paste(ImageOps.fit(tile(icons,n,5,j,3),(160,160),method=Image.Resampling.LANCZOS),(160*n,160*j))
    plates.save(dest/"roster-busts.png")
    back.save(dest/"roster-domains.jpg",quality=92)
    cards.save(dest/"roster-cards.jpg",quality=93)
    glyphs.save(dest/"roster-skills.jpg",quality=92)
    pages=[Image.new("RGBA",(CELL*6,CELL*rows)) for rows in (18,12)]
    pivots=[]; heights=[]
    for role,path in enumerate(actors):
        frames=cells(Image.open(path).convert("RGBA"),6,3)
        idle=median(f.height for f in frames[6:9])
        ratio=min(124/idle,(CELL-6)/max(max(f.size) for f in frames))
        heights.append(round(idle*ratio)); anchors=[]
        for idx,frame in enumerate(frames):
            rx=root_fraction(frame)
            f=frame.resize(tuple(max(1,round(n*ratio)) for n in frame.size),Image.Resampling.LANCZOS)
            x=(CELL-f.width)//2
            y=CELL-3-f.height+((role%3)*6+idx//6)*CELL
            anchors.append(round(x+f.width*rx))
            x+=idx%6*CELL
            pages[role//3].paste(f,(x,y))
            pages[role//3].paste(enemy(f,[2,1,3,4,3][role]),(x,y+CELL*3))
        pivots.append(anchors)
    for n,page in enumerate(pages):
        page.save(dest/f"motion-{n+3}.png")
    header="/* Generated by tools/pack_roster.py. */\nstatic const unsigned char extraPivot[5][18] = {\n"
    for row in pivots: header+="    {"+", ".join(map(str,row))+"},\n"
    header+="};\nstatic const unsigned char extraHeight[5] = {"+", ".join(map(str,heights))+"};\n"
    (ROOT/"src/roster_motion.h").write_text(header,encoding="ascii")


if __name__=="__main__":
    p=argparse.ArgumentParser()
    for name in ("portraits","domains","skills"): p.add_argument(name,type=Path)
    p.add_argument("actors",type=Path,nargs=5)
    build(**vars(p.parse_args()))
