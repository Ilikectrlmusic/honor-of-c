"""Build ready-to-embed animation pages from RGBA masters source-0..9.png.

Sheets 0..4: heroes (6 x 3); 5..8: troops and golem (6 x 2); 9: effects (5 x 2).
This is an optional asset-authoring tool; building/running the game does not use Python.
"""
import argparse
from pathlib import Path
from statistics import median
from PIL import Image

CELL = 160
ROOT = Path(__file__).resolve().parents[1]

def gutters(im, count, vertical):
    """Choose the emptiest strip near a nominal divider (do not bisect a sword)."""
    alpha = im.getchannel("A").point(lambda v: 255 if v > 55 else 0)
    if not vertical:
        alpha = alpha.transpose(Image.Transpose.TRANSPOSE)
    # A box average along the whole column gives its ink coverage.
    projection = list(alpha.resize((alpha.width, 1), Image.Resampling.BOX).getdata())
    cuts=[0]
    for k in range(1,count):
        mid=alpha.width*k/count
        wiggle=alpha.width/count*.25
        cuts.append(min(range(round(mid-wiggle),round(mid+wiggle)+1),
                        key=lambda x: sum(projection[x-1:x+2]) + abs(x-mid)*.025))
    return cuts+[alpha.width]

def cells(im, cols, rows):
    assert im.getchannel("A").getextrema()[0] < 10, "sheet lacks a transparent background"
    out=[]
    ys=gutters(im, rows, False)
    for a,b in zip(ys,ys[1:]):
        row=im.crop((0,a,im.width,b))
        xs=gutters(row,cols,True)
        for l,r in zip(xs,xs[1:]):
            tile=row.crop((l,0,r,row.height))
            bounds=tile.getchannel("A").point(lambda x: 255 if x>28 else 0).getbbox()
            assert bounds
            out.append(tile.crop(bounds))
    return out

def root_fraction(frame):
    # Register hips, NOT the box center (it moves when a weapon is extended).
    a=frame.getchannel("A")
    belt=a.crop((0,int(a.height*.57),a.width,int(a.height*.78)))
    weights=list(belt.resize((a.width,1),Image.Resampling.BOX).getdata())
    total=sum(weights); acc=0
    for x,n in enumerate(weights):
        acc+=n
        if acc>=total*.53:
            return x/a.width
    return .5

def enemy(im, role):
    h,s,v=im.convert("RGB").convert("HSV").split()
    def tint(hue):
        if role==0: return hue<18 or hue>230
        if role in (1,2,4): return 45<hue<235
        return 8<hue<46
    from PIL import ImageChops
    mask=ImageChops.multiply(h.point(lambda x:255 if tint(x) else 0),
                             s.point(lambda x:255 if x>(60 if role in (1,2,4) else 85) else 0))
    alt=Image.merge("HSV",(Image.new("L",im.size,153 if role==0 else 245),s.point(lambda x:max(145,x)),v)).convert("RGB")
    color=Image.composite(alt,im.convert("RGB"),mask)
    color.putalpha(im.getchannel("A"))
    return color

def pack(src):
    pages=[Image.new("RGBA",(CELL*6,CELL*18)) for _ in range(3)]
    pivots=[]; sizes=[]
    for role in range(9):
        rows=3 if role<5 else 2
        path=src/f"source-{role}.png"
        if role==1 and (src/"archer-clean.png").is_file(): path=src/"archer-clean.png"
        if role==5 and (src/"spear-run.png").is_file(): path=src/"spear-run.png"
        frames=cells(Image.open(path).convert("RGBA"),6,rows)
        idleHeight=median(f.height for f in frames[6:9])
        ratio=min(124/idleHeight,(CELL-6)/max(max(f.size) for f in frames))
        sizes.append(round(idleHeight*ratio))
        anchors=[]
        for idx,f in enumerate(frames):
            rx=root_fraction(f)
            f=f.resize((max(1,round(f.width*ratio)),max(1,round(f.height*ratio))),Image.Resampling.LANCZOS)
            x=(CELL-f.width)//2; y=CELL-3-f.height
            anchors.append(round(x+f.width*rx))
            row=(role%3)*6+idx//6
            xy=(idx%6*CELL+x,row*CELL+y)
            pages[role//3].paste(f,xy)
            if role!=8:
                pages[role//3].paste(enemy(f,role),(xy[0],xy[1]+CELL*3))
        pivots.append(anchors+[80]*(18-len(anchors)))
    for n,p in enumerate(pages): p.save(ROOT/f"assets/motion-{n}.png",optimize=True)
    header="/* Generated by tools/pack_motion.py. Pivot at the hips, feet on line 157. */\n"
    header+="static const unsigned char motionPivot[9][18] = {\n"
    for a in pivots: header+="    {"+", ".join(map(str,a))+"},\n"
    header+="};\nstatic const unsigned char motionHeight[9] = {"+", ".join(map(str,sizes))+"};\n"
    (ROOT/"src/motion_data.h").write_text(header,encoding="ascii")
    effects=cells(Image.open(src/"source-9.png").convert("RGBA"),5,2)
    sheet=Image.new("RGBA",(5*256,2*256))
    for i,im in enumerate(effects):
        im.thumbnail((248,248),Image.Resampling.LANCZOS)
        sheet.paste(im,(i%5*256+(256-im.width)//2,i//5*256+(256-im.height)//2))
    sheet.save(ROOT/"assets/ultimate.png",optimize=True)
    print("Packed 138 poses, enemy palettes, pivot table and ten effect textures.")

if __name__=="__main__":
    ap=argparse.ArgumentParser();ap.add_argument("masters",type=Path);pack(ap.parse_args().masters)
